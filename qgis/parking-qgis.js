window.QGISParking = (() => {

    const data = window.PARKING_QGIS_DATA;

    function pointsAttribut(points) {
        return points.map(p => p.join(",")).join(" ");
    }

    function polygones(liste, classe) {
        return liste.map(points =>
            `<polygon class="${classe}" points="${pointsAttribut(points)}" />`
        ).join("");
    }

    function afficher(conteneurId = "scene-qgis") {

        const conteneur = document.getElementById(conteneurId);

        if (!conteneur) return;

        const L = data.layers;
        const longueur20m = data.calibration.scaleBarPixels;

        conteneur.innerHTML = `
            <svg class="qgis-svg"
                 viewBox="0 0 ${data.width} ${data.height}"
                 preserveAspectRatio="none"
                 aria-label="Plan vectoriel du parking à l'échelle">

                <g class="qgis-couche qgis-emprise">
                    ${polygones(L.emprise, "qgis-emprise-polygone")}
                </g>

                <g class="qgis-couche qgis-circulations">
                    ${polygones(L.circulations, "qgis-circulation")}
                </g>

                <g class="qgis-couche qgis-noue">
                    ${polygones(L.noue, "qgis-noue-polygone")}
                </g>

                <g class="qgis-couche qgis-pieton">
                    ${polygones(L.pieton, "qgis-pieton-polygone")}
                </g>

                <g class="qgis-couche qgis-places">
                    ${polygones(L.placesStandard, "qgis-place-standard")}
                    ${polygones(L.placesPMR, "qgis-place-pmr")}
                </g>

                <g class="qgis-couche qgis-plantations">
                    ${polygones(L.ilesPlantees, "qgis-ile-plantee")}

                    ${L.arbres.map(arbre => `
                        <circle class="qgis-arbre"
                                cx="${arbre[0]}"
                                cy="${arbre[1]}"
                                r="${arbre[2]}" />
                    `).join("")}
                </g>

                <g class="qgis-echelle" transform="translate(30, ${data.height - 34})">
                    <rect x="-12" y="-23" width="${longueur20m + 78}" height="38" rx="8" />
                    <line x1="0" y1="0" x2="${longueur20m}" y2="0" />
                    <line x1="0" y1="-6" x2="0" y2="6" />
                    <line x1="${longueur20m}" y1="-6" x2="${longueur20m}" y2="6" />
                    <text x="0" y="-9">0</text>
                    <text x="${longueur20m}" y="-9" text-anchor="end">20 m</text>
                </g>
            </svg>`;
    }

    return {
        afficher,
        data
    };

})();
